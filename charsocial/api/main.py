"""Read API + admin surface.

This service never calls the model on the read path — the world is pre-generated by the
worker, so an unbounded number of viewers costs nothing. The only synchronous spend is
/api/poke, which is why it carries its own hard daily cap.

Every route declares a response model. A shape change then breaks here, loudly, instead of
reaching the frontend as a field that silently reads `undefined`.
"""
