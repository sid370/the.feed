@app.post("/api/poke", response_model=PokeOut, dependencies=[Depends(require_visitor)])
def poke(body: PokeIn) -> PokeOut:
    """A human reply. It enters the world as a post plus a notification — it does NOT
    trigger a generation. The character answers on the next tick, from the same budget as
    everyone else, which is what keeps this path from being a way to spend without limit.
    """
    # Both fields interpolate into a character's next prompt under markdown headings that
    # are structurally identical to the WORLD_RULES sections, and any poison persists via
    # memory_notes. Collapsing newlines removes the ability to forge a heading.
    if not CONFIG.poke_enabled:
        raise HTTPException(status_code=404, detail="not found")

    clean = " ".join(body.body.split())[:280]
    display_name = re.sub(r"[^a-z0-9_]", "", body.display_name.lower())[:24] or "guest"
    if not clean:
        raise HTTPException(status_code=400, detail="empty")

    with db.cursor() as cur:
        cur.execute(SQL["human_posts_today"])
        if db.one(cur)["n"] >= CONFIG.poke_daily_cap:
            raise HTTPException(status_code=429, detail="daily poke limit reached")

        cur.execute(SQL["poke_target"], {"post": body.post_id})
        target = cur.fetchone()
        if not target:
            raise HTTPException(status_code=404, detail="no such post")

        cur.execute(
            SQL["insert_human_poke"],
            {
                "world": CONFIG.world_id, "author": display_name, "body": clean,
                "parent": body.post_id, "root": target["root"],
                "character": target["character_id"],
            },
        )
        new_id = db.one(cur)["id"]
    return PokeOut(ok=True, id=str(new_id))


