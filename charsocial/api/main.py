@app.post(
    "/api/admin/characters/draft", response_model=DraftOut, dependencies=[Depends(require_admin)]
)
def draft_character(body: DraftIn) -> DraftOut:
    with db.cursor() as cur:
        result = chars.draft(cur, body.name, body.context, body.notes, body.source_material)
    if result is None:
        raise HTTPException(status_code=503, detail="no drafting provider (offline mode)")
    return DraftOut.model_validate(result)


@app.patch("/api/admin/characters/{character_id}", response_model=Ok,
           dependencies=[Depends(require_admin)])
def patch_character(character_id: str, body: PatchIn) -> Ok:
    with db.cursor() as cur:
        if body.persona_card is not None:
            cur.execute(
                "UPDATE characters SET persona_card = %s WHERE id = %s",
                (json.dumps(body.persona_card), character_id),
            )
        if body.engagement_profile is not None:
            cur.execute(
                "UPDATE characters SET engagement_profile = %s WHERE id = %s",
                (json.dumps(body.engagement_profile), character_id),
            )
        if body.status:
            chars.set_status(cur, character_id, body.status)
    return Ok()


