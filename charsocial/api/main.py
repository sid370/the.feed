SESSION_COOKIE = "cs_session"


# ------------------------------------------------------------------------------- auth


def _session_value() -> str:
    return hmac.new(CONFIG.site_password.encode(), b"charsocial", "sha256").hexdigest()[:32]


def require_visitor(request: Request) -> None:
    if not hmac.compare_digest(request.cookies.get(SESSION_COOKIE, ""), _session_value()):
        raise HTTPException(status_code=401, detail="password required")


def require_admin(request: Request) -> None:
    token = request.headers.get("x-admin-token", "")
    if not hmac.compare_digest(token, CONFIG.admin_token):
        raise HTTPException(status_code=403, detail="admin token required")


@app.post("/api/login", response_model=Ok)
def login(body: LoginIn, response: Response) -> Ok:
    if not hmac.compare_digest(body.password, CONFIG.site_password):
        raise HTTPException(status_code=401, detail="wrong password")
    response.set_cookie(
        SESSION_COOKIE, _session_value(), httponly=True, samesite="lax", max_age=60 * 60 * 24 * 30
    )
    return Ok()


@app.get("/api/health", response_model=Health)
def health() -> Health:
    return Health(ok=True, provider=CONFIG.llm_provider, world=CONFIG.world_id)


