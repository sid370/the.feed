# ------------------------------------------------------------------------------- feed




def _post_out(row) -> PostOut:
    return PostOut(
        id=str(row["id"]),
        body=row["body"],
        createdAt=row["created_at"],
        likeCount=row["like_count"],
        replyCount=row["reply_count"],
        parentId=str(row["parent_id"]) if row.get("parent_id") else None,
        replyingTo=row.get("replying_to"),
        author=Author(
            handle=row.get("handle") or "guest",
            name=row.get("name") or "Guest",
            avatarSeed=row.get("avatar_seed") or "guest",
            avatarUrl=row.get("avatar_url"),
            # A human poke has no character row, so there is no profile to open.
            isCharacter=row.get("handle") is not None,
            # Drives the parody badge. PLAN §12 calls the watermark the control that
            # makes a leaked screenshot a non-event.
            isRealPerson=bool(row.get("is_real_person")),
        ),
        headline=(
            Headline(title=row["headline_title"], url=row["headline_url"])
            if row.get("headline_title")
            else None
        ),
    )


@app.get("/api/feed", response_model=FeedOut, dependencies=[Depends(require_visitor)])
def feed(limit: int = 40, offset: int = 0) -> FeedOut:
    with db.cursor() as cur:
        cur.execute(
            SQL["feed"],
            {"world": CONFIG.world_id, "limit": min(limit, 100), "offset": max(offset, 0)},
        )
        return FeedOut(posts=[_post_out(r) for r in cur.fetchall()])


@app.get("/api/thread/{post_id}", response_model=FeedOut, dependencies=[Depends(require_visitor)])
def thread(post_id: str) -> FeedOut:
    with db.cursor() as cur:
        cur.execute(SQL["thread"], {"post": post_id})
        rows = cur.fetchall()
    if not rows:
        raise HTTPException(status_code=404, detail="not found")
    return FeedOut(posts=[_post_out(r) for r in rows])




